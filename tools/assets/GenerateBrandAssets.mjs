// Development-only conversion; product builds consume the checked-in outputs.
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
if (!process.argv[2]) throw new Error('Pass a node_modules directory containing sharp.');
const sharp = createRequire(path.join(path.resolve(process.argv[2]), '__resolve__.js'))('sharp');
const source = await fs.readFile(path.join(root, 'SingleEditorJuce/Resources/BrandMark.svg'), 'utf8');
const background = source.match(/<rect[^>]+fill="#([A-Fa-f0-9]{6})"/)?.[1];
const ink = source.match(/<path[^>]+stroke="#([A-Fa-f0-9]{6})"/)?.[1];
const radius = Number(source.match(/<rect[^>]+rx="([\d.]+)"/)?.[1]);
const stroke = Number(source.match(/stroke-width="([\d.]+)"/)?.[1]);
if (!background || !ink || !Number.isFinite(radius) || !Number.isFinite(stroke))
  throw new Error('Expected fixed square brand styling.');
const put = (name, bytes) => fs.writeFile(path.join(root, name), bytes);
const raster = size => sharp(Buffer.from(source), { density: 768 }).resize(size, size).png().toBuffer();
await put('SingleEditorJuce/Resources/AppIcon.png', await raster(1024));
const sizes = [16, 24, 32, 48, 64, 128, 256];
const images = await Promise.all(sizes.map(raster));
const directory = Buffer.alloc(6 + 16 * sizes.length);
directory.writeUInt16LE(1, 2);
directory.writeUInt16LE(sizes.length, 4);
let offset = directory.length;
images.forEach((bytes, i) => {
  const at = 6 + i * 16;
  directory[at] = directory[at + 1] = sizes[i] === 256 ? 0 : sizes[i];
  directory.writeUInt16LE(1, at + 4);
  directory.writeUInt16LE(32, at + 6);
  directory.writeUInt32LE(bytes.length, at + 8);
  directory.writeUInt32LE(offset, at + 12);
  offset += bytes.length;
});
const ico = Buffer.concat([directory, ...images]);
await put('SingleEditorJuce/Resources/AppIcon.ico', ico);
await put('icons/icon.ico', ico);
// Native painters share the SVG geometry without runtime parsing or decoding.
const data = source.match(/<path d="([^"]+)"/)?.[1];
if (!data || !/^M[\d .-]+(?: C[\d .-]+)+$/.test(data)) throw new Error('Expected one M + cubic path.');
const commands = [...data.matchAll(/([MC])([\d .-]+)/g)].map(([, command, numbers]) => {
  const values = numbers.trim().split(/\s+/).map(Number);
  if (values.length !== (command === 'M' ? 2 : 6) || values.some(x => !Number.isFinite(x)))
    throw new Error('Unexpected brand path command.');
  return `        wave.${command === 'M' ? 'startNewSubPath' : 'cubicTo'}(${values.map(x => `${x.toFixed(1)}f`).join(', ')});`;
}).join('\n');
await put('SingleEditorJuce/Source/UI/LookAndFeel/BrandMark.h', `// Generated by tools/assets/GenerateBrandAssets.mjs from Resources/BrandMark.svg.
#pragma once
#include <juce_graphics/juce_graphics.h>

namespace singleeditor
{
struct BrandMark final
{
    static void paint(juce::Graphics& g, juce::Rectangle<float> bounds)
    {
        if (bounds.isEmpty()) return;
        const juce::Graphics::ScopedSaveState saved(g);
        const auto side = juce::jmin(bounds.getWidth(), bounds.getHeight());
        bounds = bounds.withSizeKeepingCentre(side, side);
        g.addTransform(juce::AffineTransform::scale(side / 128.0f).translated(bounds.getX(), bounds.getY()));
        g.setColour(juce::Colour(0xff${background.toLowerCase()}));
        g.fillRoundedRectangle(0.0f, 0.0f, 128.0f, 128.0f, ${radius.toFixed(1)}f);
        juce::Path wave;
${commands}
        g.setColour(${ink.toLowerCase() === 'ffffff' ? 'juce::Colours::white' : `juce::Colour(0xff${ink.toLowerCase()})`});
        g.strokePath(wave, juce::PathStrokeType(${stroke.toFixed(1)}f, juce::PathStrokeType::curved, juce::PathStrokeType::rounded));
    }
};
}
`);
console.log(JSON.stringify({ png: 1024, icoSizes: sizes, icoBytes: ico.length, nativeGeometry: 'generated' }));
